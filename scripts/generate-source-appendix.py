@dataclass(frozen=True)
class SectionSpec:
    title: str
    roots: tuple[str, ...] = ()
    explicit_files: tuple[str, ...] = ()
    allowed_suffixes: tuple[str, ...] = ()
    excluded_prefixes: tuple[str, ...] = ()


